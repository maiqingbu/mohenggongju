/**
 * 获取指定 AI 动作的模板信息
 * @param action AI 动作 key
 * @param platformId 平台 ID（如 'fanqie', 'qidian'），可选
 * @returns 模板信息
 */
export function getTemplate(action: AiActionKey, platformId?: string | null): TemplateInfo {
  if (platformId) {
    const platformTemplates = PLATFORM_TEMPLATES[platformId]
    if (platformTemplates?.[action]) {
      return platformTemplates[action]
    }
  }
  return DEFAULT_TEMPLATES[action] || { name: '通用模板', author: '系统内置', desc: '' }
}

/**
 * 注入/更新平台专用模板
 * @param platformId 平台 ID
 * @param templates 模板映射表
 */
export function setPlatformTemplates(platformId: string, templates: Record<string, TemplateInfo>) {
  if (!PLATFORM_TEMPLATES[platformId]) {
    PLATFORM_TEMPLATES[platformId] = {}
  }
  Object.assign(PLATFORM_TEMPLATES[platformId], templates)
}
